const dictionary: Record<PortalLocale, AdminOnboardingCopy> = { fa, en, ar, tr, es, ku, de, fr };

export function adminOnboardingCopy(locale: PortalLocale) {
  return dictionary[locale] ?? en;
}

export function adminAudienceLabel(copy: AdminOnboardingCopy, audience: string) {
  return copy.audiences[audience] || audience;
}

export function adminEventActionLabel(copy: AdminOnboardingCopy, action: string) {
  return copy.eventActions[action] || action.replaceAll("_", " ");
}

export function adminApprovalError(copy: AdminOnboardingCopy, code: string, fallback: string) {
  return copy.approvalErrors[code] || fallback || copy.approvalErrors.approval_failed;
}
