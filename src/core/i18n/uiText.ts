function englishLabel(key: string) {
  const normalized = key.replaceAll("_", " ");
  return normalized ? normalized[0].toUpperCase() + normalized.slice(1) : normalized;
}

function exactTranslation(text: string, locale: PortalLocale) {
  const key = sourceKey(text);
  if (!key) return undefined;
  if (locale === "en") return englishLabel(key);
  return rows[key]?.[locale as Exclude<PortalLocale, "en">] || englishLabel(key);
}

export function translateUiText(text: string, localeValue?: string | null): string {
  const locale = normalizePortalLocale(localeValue).locale;
  if (!text.trim()) return text;
  const exact = exactTranslation(text, locale);
  if (exact) return preserveWhitespace(text, exact);
  if (locale === "en" || technicalPattern.test(text.trim()) || urlOrPathPattern.test(text.trim())) return text;

  // Never translate isolated words inside an unknown sentence. Partial replacement
  // produced hybrid strings such as Persian labels mixed with English nouns and
  // verbs. A phrase must have a complete catalog translation; otherwise the
  // complete source phrase is preserved until a proper translation is added.
  return text;
}

function preserveWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}
