function splitWhitespace(value: string) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return { leading, trailing, core: value.slice(leading.length, value.length - trailing.length) };
}

export function translatePortalText(localeValue: string | null | undefined, source: string) {
  const locale = normalizePortalLocale(localeValue).locale;
  if (!source.trim()) return source;
  const { leading, trailing, core } = splitWhitespace(source);
  const canonical = reverseCopy.get(core) || core;
  if (locale === "en") {
    if (canonical !== core) return `${leading}${canonical}${trailing}`;
    const fragment = core.match(/^([^A-Za-z\u0600-\u06FF]*)([A-Za-z\u0600-\u06FF][\s\S]*?[A-Za-z\u0600-\u06FF])([^A-Za-z\u0600-\u06FF]*)$/);
    if (fragment) {
      const innerCanonical = reverseCopy.get(fragment[2]) || fragment[2];
      if (innerCanonical !== fragment[2]) return `${leading}${fragment[1]}${innerCanonical}${fragment[3]}${trailing}`;
    }
    return source;
  }
  const direct = portalCopy[canonical]?.[locale] || sharedCopy[canonical]?.[locale] || portalCopy[core]?.[locale] || sharedCopy[core]?.[locale];
  if (direct) return `${leading}${direct}${trailing}`;
  const sharedUi = translateUiText(canonical, localeValue);
  if (sharedUi !== canonical) return `${leading}${sharedUi}${trailing}`;

  // Dynamic JSX often produces small punctuation-wrapped fragments such as
  // " · unread " or "% · valid until ". Translate only when the inner
  // phrase is a complete catalog entry; never translate arbitrary sentence parts.
  const fragment = core.match(/^([^A-Za-z\u0600-\u06FF]*)([A-Za-z\u0600-\u06FF][\s\S]*?[A-Za-z\u0600-\u06FF])([^A-Za-z\u0600-\u06FF]*)$/);
  if (fragment) {
    const inner = fragment[2];
    const innerCanonical = reverseCopy.get(inner) || inner;
    const innerDirect = portalCopy[innerCanonical]?.[locale] || sharedCopy[innerCanonical]?.[locale];
    const innerUi = innerDirect || translateUiText(innerCanonical, localeValue);
    if (innerUi && innerUi !== innerCanonical) return `${leading}${fragment[1]}${innerUi}${fragment[3]}${trailing}`;
  }
  return source;
}

export function hasPortalTranslation(localeValue: string | null | undefined, source: string) {
  const locale = normalizePortalLocale(localeValue).locale;
  const canonical = reverseCopy.get(source.trim()) || source.trim();
  return locale === "en" ? canonical !== source.trim() || Boolean(canonical) : Boolean(portalCopy[canonical]?.[locale] || sharedCopy[canonical]?.[locale]);
}
