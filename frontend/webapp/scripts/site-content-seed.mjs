/**
 * Writes the seed migration for the editorial pages and FAQs from
 * src/features/site-content/seed/content (see seed/index.ts).
 *
 *   node scripts/site-content-seed.mjs db/migrations/0086_site_content_seed.sql
 *
 * Insert-only: a page that already exists (by slug) or an FAQ already seeded
 * (by seed_key) is left untouched, so admin edits are never overwritten. A
 * released migration is immutable: later content changes need a new file.
 *
 * The Lexical shape here must match src/features/site-content/lib/lexical.ts;
 * site-content.test.ts checks the generated SQL against that module.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(root, "src/features/site-content/seed/content");

export const PAGE_FILES = [
  "about-us", "services", "contact-us", "licenses-certifications", "pricing-fees",
  "shipping-delivery", "returns-refunds", "terms-conditions", "privacy-policy",
];
export const FAQ_FILES = [
  "home", "explore", "search", "map", "categories", "provider", "specialist", "service", "shop", "tours", "gym",
];
const RTL = new Set(["fa-IR", "ar-SA", "ku-KU"]);

const textNode = (text) => ({ detail: 0, format: 0, mode: "normal", style: "", text, type: "text", version: 1 });
const element = (type, children, extra = {}) => ({ children, direction: null, format: "", indent: 0, type, version: 1, ...extra });
const blockNode = (block) =>
  block.type === "h2" || block.type === "h3"
    ? element("heading", [textNode(block.text)], { tag: block.type })
    : block.type === "quote"
      ? element("quote", [textNode(block.text)])
      : element("paragraph", [textNode(block.text)], { textFormat: 0, textStyle: "" });
export const blocksToLexical = (blocks, direction = "ltr") =>
  JSON.stringify({ root: element("root", blocks.map(blockNode), { direction }) });
export const textToLexical = (text, direction = "ltr") =>
  blocksToLexical(
    text.split(/\n{2,}/u).map((part) => part.trim()).filter(Boolean).map((part) => ({ type: "p", text: part })),
    direction,
  );
const dir = (key) => (RTL.has(key) ? "rtl" : "ltr");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const mapLocales = (locales, fn) => Object.fromEntries(Object.entries(locales).map(([key, value]) => [key, fn(value, key)]));

function faqPair(locales) {
  const question = {};
  const answer = {};
  for (const [key, copy] of Object.entries(locales)) {
    if (!copy?.q?.trim() || !copy?.a?.trim()) continue;
    question[key] = copy.q.trim();
    answer[key] = textToLexical(copy.a, dir(key));
  }
  return { question, answer };
}

export function buildSeed() {
  const pages = PAGE_FILES.map((slug) => readJson(join(contentDir, "pages", `${slug}.json`)));
  const pageRows = pages.map((file, index) => ({
    slug: file.slug,
    isPublished: file.status === "publish",
    displayOrder: index,
    title: mapLocales(file.locales, (copy) => copy.title.trim()),
    summary: mapLocales(file.locales, (copy) => copy.metaDescription.trim()),
    body: mapLocales(file.locales, (copy, key) => blocksToLexical(copy.blocks, dir(key))),
  }));

  const faqRows = [];
  for (const file of pages) {
    const count = Math.max(0, ...Object.values(file.locales).map((copy) => copy.faq?.length ?? 0));
    for (let index = 0; index < count; index += 1) {
      const locales = mapLocales(file.locales, (copy) => copy.faq?.[index]);
      faqRows.push({ seedKey: `site_page:${file.slug}:${index}`, scope: "site_page", entityKey: file.slug, displayOrder: index, ...faqPair(locales) });
    }
  }
  for (const name of FAQ_FILES) {
    const file = readJson(join(contentDir, "faqs", `${name}.json`));
    file.items.forEach((item, index) => {
      faqRows.push({
        seedKey: `${file.scope}:${file.entityKey ?? ""}:${index}`,
        scope: file.scope,
        entityKey: file.entityKey ?? null,
        displayOrder: index,
        ...faqPair(item.locales),
      });
    });
  }
  return { pageRows, faqRows };
}

// Dollar-quoted literals: the content has quotes and apostrophes in 11 languages.
function literal(value) {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  let tag = "seed";
  while (text.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${text}$${tag}$`;
}

export function renderSql({ pageRows, faqRows }) {
  const lines = [
    "-- Launch content for admin → Editorial (generated by scripts/site-content-seed.mjs",
    "-- from src/features/site-content/seed/content; do not edit by hand).",
    "-- Insert-only: existing pages (by slug) and already-seeded FAQs (by seed_key) are",
    "-- left as the admin edited them. Pages whose facts still need the owner's",
    "-- confirmation are inserted as drafts (is_published = false).",
    "",
  ];
  for (const row of pageRows) {
    lines.push(
      "insert into content.site_pages (slug, title_translations, summary_translations, body_translations, is_published, show_in_footer, display_order)",
      `values (${literal(row.slug)}, ${literal(row.title)}::jsonb, ${literal(row.summary)}::jsonb, ${literal(row.body)}::jsonb, ${row.isPublished}, true, ${row.displayOrder})`,
      "on conflict (slug) do nothing;",
      "",
    );
  }
  for (const row of faqRows) {
    lines.push(
      "insert into content.faq_items (seed_key, scope, entity_key, question_translations, answer_translations, display_order)",
      `values (${literal(row.seedKey)}, ${literal(row.scope)}, ${row.entityKey ? literal(row.entityKey) : "null"}, ${literal(row.question)}::jsonb, ${literal(row.answer)}::jsonb, ${row.displayOrder})`,
      "on conflict (seed_key) do nothing;",
      "",
    );
  }
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = process.argv[2];
  if (!target) {
    console.error("usage: node scripts/site-content-seed.mjs <output.sql>");
    process.exit(1);
  }
  const seed = buildSeed();
  writeFileSync(join(root, target), renderSql(seed));
  console.log(`wrote ${target}: ${seed.pageRows.length} pages, ${seed.faqRows.length} FAQ items`);
}
