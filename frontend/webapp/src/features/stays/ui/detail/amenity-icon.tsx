/** stay.amenities.icon (a lucide name) → component. Unknown names get a check mark. */
const ICONS: Record<string, LucideIcon> = {
  wifi: Wifi,
  car: Car,
  clock: Clock,
  "arrow-up-down": ArrowUpDown,
  plane: Plane,
  moon: Moon,
  luggage: Luggage,
  shirt: Shirt,
  banknote: Banknote,
  map: Map,
  "shopping-bag": ShoppingBag,
  snowflake: Snowflake,
  flame: Flame,
  landmark: Landmark,
  tv: Tv,
  refrigerator: Refrigerator,
  "cooking-pot": CookingPot,
  lock: Lock,
  "cigarette-off": CigaretteOff,
  bath: Bath,
  coffee: Coffee,
  utensils: Utensils,
  bell: Bell,
  waves: Waves,
  dumbbell: Dumbbell,
  thermometer: Thermometer,
  hand: Hand,
  scissors: Scissors,
  users: Users,
  baby: Baby,
  "gamepad-2": Gamepad2,
  accessibility: Accessibility,
  hospital: Hospital,
  "heart-handshake": HeartHandshake,
  presentation: Presentation,
  briefcase: Briefcase,
  trees: Trees,
  sunset: Sunset,
};

export function AmenityIcon({ name, className }: { name: string | null | undefined; className?: string }) {
  const Icon = (name && ICONS[name]) || Check;
  return <Icon className={className} aria-hidden="true" />;
}
