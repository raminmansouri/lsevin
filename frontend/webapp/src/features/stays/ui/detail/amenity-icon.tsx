export const amenityIcons = Object.keys(ICONS).sort();

export function hasAmenityIcon(name: string | null | undefined): boolean {
  return !!name && Object.prototype.hasOwnProperty.call(ICONS, name);
}

/** The amenity's own image (from the media library) when it has one, else its icon. */
export function AmenityIcon({ name, className, imageUrl }: { imageUrl?: string | null; name: string | null | undefined; className?: string }) {
  const Icon = name && hasAmenityIcon(name) ? ICONS[name] : Check;
  // eslint-disable-next-line @next/next/no-img-element -- tiny media-library icon, already sized by the caller
  if (imageUrl) return <img alt="" aria-hidden="true" src={resolveMediaUrl(imageUrl)} loading="lazy" decoding="async" className={className} />;
  return <Icon className={className} aria-hidden="true" />;
}
