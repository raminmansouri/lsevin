-- identity-by-default.sql - run ONCE on BOTH servers (A and B), same file.
-- SymmetricDS inserts each replicated row with the id it had on the other node. PostgreSQL refuses that for
-- GENERATED ALWAYS identity columns ("cannot insert a non-DEFAULT value into column"), which blocks the whole
-- 'business' channel behind one failing batch. BY DEFAULT keeps auto-numbering for normal inserts and accepts
-- explicit ids from replication. No data is rewritten; sequences and their current values are unchanged.
-- Undo (only if no replicated rows have been applied yet): alter ... alter column <col> set generated always;
alter table accounting.panel_login_attempts alter column id  set generated by default;
alter table accounting.wallet_ledger        alter column seq set generated by default;
alter table patient.audit_log               alter column id  set generated by default;
alter table shop.analytics_events           alter column id  set generated by default;
alter table accounting.audit_log            alter column id  set generated by default;

select 'remaining GENERATED ALWAYS identity columns: ' || count(*)
from information_schema.columns
where identity_generation = 'ALWAYS' and table_schema not in ('pg_catalog', 'information_schema');
